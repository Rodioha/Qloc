def get_plant_info(plant_name):
    """Возвращает информацию о растении по названию (с нечётким поиском)."""
    if not plant_name:
        return _default_plant(plant_name)

    search = plant_name.lower().strip()

    # 1. Точное совпадение
    for key in plants_info:
        if key.lower() == search:
            return {"name": key, **plants_info[key]}

    # 2. Частичное совпадение (вхождение подстроки)
    for key in plants_info:
        if search in key.lower() or key.lower() in search:
            return {"name": key, **plants_info[key]}

    # 3. По первому слову (например, «Морошка» найдёт «Морошка болотная»)
    first_word = search.split()[0]
    for key in plants_info:
        if key.lower().startswith(first_word):
            return {"name": key, **plants_info[key]}

    return _default_plant(plant_name)


def find_plant_by_partial_name(partial_name):
    """Находит полное название растения по частичному совпадению."""
    if not partial_name:
        return None
    search = partial_name.lower().strip()
    for key in plants_info:
        if search in key.lower() or key.lower() in search:
            return key
    first_word = search.split()[0]
    for key in plants_info:
        if key.lower().startswith(first_word):
            return key
    return None


